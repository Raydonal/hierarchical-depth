def _trim(ax):
    ax.spines[["top", "right"]].set_visible(False)


def fig1_nested_reservoirs_and_B():
    fig, axes = plt.subplots(1, 2, figsize=(9.5, 4.0), constrained_layout=True)

    # Left: not a cartoon -- an ancestral Monte Carlo simulation of the
    # actual chain (s = 1/2, a_i = 2 at every level), 20,000 replicate paths
    # T_0 -> T_1 -> ... -> T_3, T_0 = 1 fixed. Each level's conditional draw
    # relaxes toward the temperature above it (mean T_{i-1}) but adds
    # variance, so the marginal of log T_i visibly widens with depth; this
    # is the structure Sections 4-6 exploit (deeper chains are more spread
    # in log-temperature), not just a labeled diagram of the recursion.
    ax = axes[0]
    rng = np.random.default_rng(0)
    n_paths = 20000
    depths = [0, 1, 2, 3]
    a_level = 2.0
    T = np.full(n_paths, 1.0)
    logT_by_depth = {0: np.log(T)}
    for level in range(1, max(depths) + 1):
        T = sample_conditional(T, a_level, 0.5, rng)
        logT_by_depth[level] = np.log(T)
    grid = np.linspace(-3.5, 3.5, 400)
    offsets = np.arange(len(depths))[::-1] * 1.15
    for depth, offset, color in zip(depths, offsets, SEQ_CMAP(np.linspace(0.15, 0.85, len(depths)))):
        # T_0 is a fixed constant (a point mass at log T_0 = 0), not a random
        # draw, so gaussian_kde's covariance estimate is singular there; draw
        # it as a narrow spike instead of fitting a density to zero variance.
        if depth == 0:
            density = np.exp(-0.5 * (grid / 0.03) ** 2)
        else:
            density = gaussian_kde(logT_by_depth[depth])(grid)
        density = density / density.max() * 0.95
        ax.fill_between(grid, offset, offset + density, color=color, alpha=0.85, lw=0)
        ax.plot(grid, offset + density, color=color, lw=1.0)
        ax.text(-3.4, offset + 0.15, f"$T_{depth}$", fontsize=11, va="bottom")
    ax.set_yticks([])
    ax.set_xlabel(r"$\log T_i$")
    ax.set_ylim(-0.15, offsets[0] + 1.1)
    for spine in ("top", "right", "left"):
        ax.spines[spine].set_visible(False)
    ax.set_title("Simulated chain: $\\log T_i$ widens with depth")

    # Right: B(E) at fixed a = 1, s = 1/2, varying N -- curves close in the
    # bulk, separating only in the tail (log y-axis makes the separation
    # visible at all).
    ax = axes[1]
    E = np.linspace(0, 8, 300)
    colors = SEQ_CMAP(np.linspace(0.1, 0.85, 4))
    for N, color in zip(range(4), colors):
        a_vec = [1.0] * N
        Bvals = B(E, a_vec, 0.5) if N > 0 else np.exp(-E)
        ax.plot(E, Bvals, color=color, lw=1.7, label=f"$N = {N}$")
    ax.set_yscale("log")
    ax.set_xlabel(r"$E$")
    ax.set_ylabel(r"$B(E)$")
    ax.set_title(r"Same mean, different depth ($a=1$, $s=1/2$)")
    ax.legend(frameon=False)
    _trim(ax)

    for ext in ("pdf", "png"):
        fig.savefig(FIGURES / f"fig_cascade_and_B.{ext}", dpi=200)
    plt.close(fig)


def fig2_identifiability(numbers):
    fig, axes = plt.subplots(1, 2, figsize=(9.5, 4.0), constrained_layout=True)

    ax = axes[0]
    a_grid = np.array(numbers["kappa_ratio_curve"]["a"])
    ratio = np.array(numbers["kappa_ratio_curve"]["ratio"])
    ax.plot(a_grid, ratio, color=QUAL[0], lw=1.8)
    ax.set_xscale("log")
    ax.set_xlabel(r"$a$")
    ax.set_ylabel(r"$\kappa_3/\kappa_2$")
    ax.set_title("Log-cumulant ratio: the map the estimator inverts")
    _trim(ax)

    ax = axes[1]
    by_depth = {k: {n: v["rate"] for n, v in pc.items()}
                for k, pc in numbers["power_by_depth"]["by_N_true"].items()}
    depths = sorted(int(k) for k in by_depth)
    colors = SEQ_CMAP(np.linspace(0.15, 0.85, len(depths)))
    for depth, color in zip(depths, colors):
        pc = by_depth[str(depth)]
        ns = sorted(int(k) for k in pc)
        powers = [pc[str(n)] for n in ns]
        label = r"$N_{\mathrm{true}}=1$ (test size)" if depth == 1 else f"$N_{{\\mathrm{{true}}}}={depth}$"
        ax.plot(ns, powers, "o-", color=color, lw=1.8, markersize=5, label=label)
    ax.axhline(0.05, color="0.6", lw=1, ls="--")
    ax.set_xscale("log")
    ax.set_xlabel(r"sample size $n$")
    ax.set_ylabel(r"rejection rate at $H_0\!: N=1$")
    ax.set_ylim(-0.03, 1.03)
    ax.set_title(r"Size ($N_{\mathrm{true}}=1$) and power ($N_{\mathrm{true}}>1$)")
    ax.legend(frameon=False, fontsize=7.5, loc="center right")
    _trim(ax)

    for ext in ("pdf", "png"):
        fig.savefig(FIGURES / f"fig_identifiability.{ext}", dpi=200)
    plt.close(fig)


def fig3_network_schematic():
    # A single realized draw from the model, not a decorative cartoon: two
    # level-2 communities inside one level-1 community (N=2), each
    # community's connection-propensity factor X_{i,c} drawn from the same
    # Gamma(a_i, mean 1) law as a reservoir level (background.sample_conditional),
    # multiplied down to W_v = X_1 * X_2, and vertex degrees drawn
    # D_v | W_v ~ Poisson(lambda W_v) exactly as in Eq. (Wv). Edges are then
    # placed by the Chung-Lu expected-degree rule (already cited in the text)
    # within each leaf community, plus a small constant cross-community rate --
    # so node size, and which nodes connect, both trace back to the same
    # simulated W_v and D_v, not to independent random decoration.
    rng = np.random.default_rng(3)
    a1, a2, lam = 4.0, 4.0, 7.0
    n_per_group = 7
    X1 = sample_conditional(np.array(1.0), a1, 0.5, rng)
    X2 = sample_conditional(np.array([1.0, 1.0]), a2, 0.5, rng)
    W = X1 * X2  # length-2: one connection propensity per leaf community
    D = [rng.poisson(lam * W[g], size=n_per_group) for g in range(2)]

    fig, ax = plt.subplots(figsize=(6.5, 4.2), constrained_layout=True)
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 6)
    ax.axis("off")

    outer = FancyBboxPatch((0.4, 0.4), 9.2, 5.2, boxstyle="round,pad=0.1",
                            linewidth=1.4, edgecolor=QUAL[0], facecolor="none")
    ax.add_patch(outer)
    ax.text(0.7, 5.3, "level 1 community", fontsize=9, color=QUAL[0])

    positions, sizes, colors_per_node = [], [], []
    group_slices, group_colors = [], []
    for cx, color, Dg in zip((2.8, 7.2), (QUAL[1], QUAL[2]), D):
        inner = FancyBboxPatch((cx - 2.0, 1.0), 4.0, 3.6, boxstyle="round,pad=0.08",
                                linewidth=1.2, edgecolor=color, facecolor="none")
        ax.add_patch(inner)
        ax.text(cx - 1.8, 4.35, "level 2 community", fontsize=8, color=color)
        pts = rng.uniform([cx - 1.6, 1.4], [cx + 1.6, 4.2], size=(n_per_group, 2))
        start = len(positions)
        positions.extend(pts)
        sizes.extend(Dg)
        colors_per_node.extend([color] * n_per_group)
        group_slices.append(slice(start, start + n_per_group))
        group_colors.append(color)

    positions = np.array(positions)
    sizes = np.array(sizes, dtype=float)
    # Chung-Lu: P(edge u,v) proportional to d_u d_v, capped at 1, separately
    # calibrated within each leaf community; a small constant rate joins the
    # two communities (the "few edges between communities" that motivate
    # calling this a nested, not a fully separated, structure).
    for sl, color in zip(group_slices, group_colors):
        d = sizes[sl]
        n = len(d)
        denom = d.sum() if d.sum() > 0 else 1.0
        for i in range(n):
            for j in range(i + 1, n):
                p = min(1.0, 1.4 * d[i] * d[j] / denom)
                if rng.random() < p:
                    pi, pj = positions[sl][i], positions[sl][j]
                    ax.plot([pi[0], pj[0]], [pi[1], pj[1]], color=color,
                            lw=0.6, alpha=0.6, zorder=1)
    n0 = len(D[0])
    for i in range(n0):
        for j in range(len(D[1])):
            if rng.random() < 0.03:
                pi = positions[i]
                pj = positions[n0 + j]
                ax.plot([pi[0], pj[0]], [pi[1], pj[1]], color="0.6", lw=0.5,
                        alpha=0.5, zorder=0)
    ax.scatter(positions[:, 0], positions[:, 1], s=25 + 14 * sizes,
               color=colors_per_node, zorder=3, edgecolor="white", linewidth=0.4)

    ax.text(5, -0.15,
            r"$W_v = X_1\cdot X_{2,c(v)}$, $D_v\mid W_v \sim \mathrm{Poisson}(\lambda W_v)$"
            f"   ($\\hat W = {W[0]:.2f}, {W[1]:.2f}$; node size $\\propto D_v$)",
            ha="center", va="top", fontsize=9)
    ax.set_title("Nested communities as a graph-side cascade (one simulated draw)")

    for ext in ("pdf", "png"):
        fig.savefig(FIGURES / f"fig_network_schematic.{ext}", dpi=200)
    plt.close(fig)


def fig4_cross_dataset_summary():
    # Every number here was re-run from scripts/analyze_*.py this session
    # (not copied from an earlier draft). Two panels, one per finding, rather
    # than one axis trying to carry both: the top panel is the group where
    # branch and depth agree (stretched-exponential, N_round=1) and the only
    # question left is whether the test rejects, so p-value is the natural
    # x-axis; the bottom panel is C. elegans, where branch also agrees
    # (power-law) but N_round itself disagrees across degree types by more
    # than a factor of six, so N_round is the natural x-axis there instead.
    # Squeezing both onto one N_round axis (the previous version of this
    # figure) buried the first finding, since eight of eleven rows sit at the
    # same N_round=1 and differ only in p-value.
    top_rows = [
        ("email-Eu-core, out-degree", 0.391),
        ("OpenFlights, out-degree", 0.200),
        ("Turbulence, lag 2 ms", 0.0000),
        ("Turbulence, lag 5 ms", 0.0000),
        ("Turbulence, lag 10 ms", 0.0000),
        ("Turbulence, lag 20 ms", 0.0000),
        ("Turbulence, lag 50 ms", 0.356),
        ("Turbulence, lag 100 ms", 0.368),
    ]
    bottom_rows = [
        ("out-degree", 4, 1.000),
        ("total-degree", 7, 0.998),
        ("in-degree", 26, 1.000),
    ]

    fig, (ax1, ax2) = plt.subplots(
        2, 1, figsize=(7.5, 5.6), constrained_layout=True,
        gridspec_kw={"height_ratios": [8, 3]},
    )

    ys1 = np.arange(len(top_rows))[::-1]
    p_floor = 2e-4
    for y, (label, p) in zip(ys1, top_rows):
        p_plot = max(p, p_floor)
        reject = p < 0.05
        color = QUAL[3] if reject else QUAL[0]
        ax1.scatter([p_plot], [y], s=110, color=color, zorder=3,
                    edgecolor="black", linewidth=0.6)
        p_label = "<0.0001" if p < 1e-4 else f"{p:.3f}"
        ax1.text(p_plot * 1.4, y, f"$p={p_label}$", va="center", fontsize=8.5)
    ax1.axvline(0.05, color="0.4", lw=1, ls="--")
    ax1.text(0.05, -1.0, "reject $\\rightarrow$    $\\leftarrow$ do not reject",
              fontsize=7.5, color="0.35", ha="center", va="top")
    ax1.set_xscale("log")
    ax1.set_xlim(p_floor * 0.6, 1.0)
    ax1.set_ylim(-1.6, len(top_rows) - 0.3)
    ax1.set_yticks(ys1)
    ax1.set_yticklabels([r[0] for r in top_rows])
    ax1.set_xlabel(r"bootstrap $p$-value, $H_0\!: N=1$ (log scale)")
    ax1.set_title("Stretched-exponential branch, $N_{\\mathrm{round}}=1$ throughout: does the test reject?")
    _trim(ax1)

    ys2 = np.arange(len(bottom_rows))[::-1]
    for y, (label, n_round, p) in zip(ys2, bottom_rows):
        ax2.scatter([n_round], [y], s=110, color=QUAL[3], zorder=3,
                    edgecolor="black", linewidth=0.6)
        ax2.text(n_round + 1.0, y, f"$p={p:.3f}$", va="center", fontsize=8.5)
    ax2.set_yticks(ys2)
    ax2.set_yticklabels([r[0] for r in bottom_rows])
    ax2.set_xlim(0, 32)
    ax2.set_xlabel(r"$N_{\mathrm{round}}$")
    ax2.set_title("Power-law branch, C. elegans: same branch, depth disagrees by degree type")
    _trim(ax2)

    for ext in ("pdf", "png"):
        fig.savefig(FIGURES / f"fig_cross_dataset_summary.{ext}", dpi=200)
    plt.close(fig)


def main():
    if "--legacy" not in sys.argv:
        raise SystemExit(
            "This script is superseded by scripts/make_theory_figures.py and "
            "scripts/make_data_figures.py (`make figures`). Its old outputs in "
            "figures/ are kept untouched because the manuscript may still "
            "reference them; pass --legacy to regenerate them anyway.")
    FIGURES.mkdir(exist_ok=True)
    numbers_path = FIGURES.parent / "results" / "compute_article_numbers.json"
    if not numbers_path.exists():
        raise SystemExit("run scripts/compute_article_numbers.py first")
    numbers = json.loads(numbers_path.read_text())

    fig1_nested_reservoirs_and_B()
    fig2_identifiability(numbers)
    fig3_network_schematic()
    fig4_cross_dataset_summary()
    print("wrote fig_cascade_and_B, fig_identifiability, fig_network_schematic, "
          "fig_cross_dataset_summary (.pdf + .png) to", FIGURES)


if __name__ == "__main__":
    main()
