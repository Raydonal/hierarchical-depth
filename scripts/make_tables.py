#!/usr/bin/env python3
"""Write the manuscript's LaTeX tables from ``results/*.json`` -- no number in
``article/generated/*.tex`` is typed by hand.

    tab_topology.tex    descriptive topology of the three networks
    tab_power.tex       empirical size/power of the depth test (rate (MC s.e.))
    tab_empirical.tex   every empirical series: estimates, 95% CIs, depth test

Each file holds only ``tabular`` material (booktabs, ``\\small``), sized for the
390 pt text width; the manuscript supplies the ``table`` float and caption.

Run from the repo root (after the analysis scripts)::

    PYTHONPATH=. python3 scripts/make_tables.py
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from scripts import common  # noqa: E402

OUT = REPO_ROOT / "article" / "generated"
SYSTEM_TEX = {
    "email-Eu-core": r"\texttt{email-Eu-core}",
    "OpenFlights": "OpenFlights",
    "C. elegans": r"\textit{C.~elegans}",
}
DASH = "---"


def sig(x, digits=3):
    """``digits`` significant digits, plain decimal notation, minus as math."""
    if x is None or not math.isfinite(x):
        return DASH
    if x == 0:
        return "0"
    decimals = max(0, digits - 1 - int(math.floor(math.log10(abs(x)))))
    text = f"{round(x, decimals):.{decimals}f}"
    return f"$-${text[1:]}" if text.startswith("-") else text


def integer(n):
    return str(n)


def pval(p):
    if p is None:
        return DASH
    if p < 0.001:
        return r"$<$0.001"
    return f"{p:.3f}" if p < 0.01 else f"{p:.2f}"


def ci(c, digits=3):
    return DASH if c is None else f"[{sig(c[0], digits)}, {sig(c[1], digits)}]"


def header(script_sources):
    return (f"% Generated by scripts/make_tables.py from {script_sources}.\n"
            "% Do not edit by hand: rerun `make tables`.\n")


def write(name, text):
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / name
    path.write_text(text)
    print(f"wrote {path.relative_to(REPO_ROOT)}")


# --------------------------------------------------------------------------


def tab_topology():
    nets = common.read_json("network_topology")["networks"]
    rows = []
    for name in ("email-Eu-core", "OpenFlights", "C. elegans"):
        d = nets[name]
        rows.append(" & ".join([
            SYSTEM_TEX[name], integer(d["n_nodes"]), integer(d["n_edges_undirected"]),
            sig(d["density"]), sig(d["mean_degree"]), sig(d["global_clustering"]),
            sig(d["degree_assortativity"]),
        ]) + r" \\")
    body = "\n".join(rows)
    write("tab_topology.tex", header("results/network_topology.json") + rf"""{{\small
\setlength{{\tabcolsep}}{{4pt}}
\begin{{tabular}}{{@{{}}lrrrrrr@{{}}}}
\toprule
Network & Nodes & Edges & Density & Mean deg. & Transitivity & Assortativity \\
\midrule
{body}
\bottomrule
\end{{tabular}}
}}
""")


def tab_power():
    pbd = common.read_json("compute_article_numbers")["power_by_depth"]
    sizes = pbd["sample_sizes"]
    rows = []
    for key in sorted(pbd["by_N_true"], key=int):
        cells = [f"{pbd['by_N_true'][key][str(n)]['rate']:.2f} "
                 f"({pbd['by_N_true'][key][str(n)]['se']:.2f})" for n in sizes]
        rows.append(f"{key} & " + " & ".join(cells) + r" \\")
    head = " & ".join(f"$n={integer(n)}$" for n in sizes)
    body = "\n".join(rows)
    write("tab_power.tex", header("results/compute_article_numbers.json") + rf"""{{\small
\setlength{{\tabcolsep}}{{6pt}}
\begin{{tabular}}{{@{{}}c{'c' * len(sizes)}@{{}}}}
\toprule
$N_{{\mathrm{{true}}}}$ & {head} \\
\midrule
{body}
\bottomrule
\end{{tabular}}
}}
""")


def _class_rows(label, rec, dispersion, blank=""):
    """One table row per admissible class of a series."""
    rows = []
    for key in ("0.5", "1"):
        c = rec["classes"][key]
        if c["status"] != "ok":
            continue
        rows.append(" & ".join([
            label, integer(rec["n"]), dispersion, "$1/2$" if key == "0.5" else "$1$",
            f"{sig(c['a_hat'])} {ci(c['ci_a_hat'])}",
            f"{sig(c['N_hat'])} {ci(c['ci_N_hat'])}",
            str(c["N_round"]), pval(c["p_value"]),
        ]) + r" \\")
        label = blank
    return rows


N_COLS = 8
TABCOLSEP = "3pt"   # 4pt overflows the 390 pt text width in this table
CI_DIGITS = 3


def _group(title, first, n_cols=N_COLS):
    """A left-aligned group heading spanning the table."""
    lines = [] if first else [r"\addlinespace"]
    lines.append(rf"\multicolumn{{{n_cols}}}{{@{{}}l}}{{{title}}} \\")
    return lines


def tab_empirical():
    sources = ("analyze_email_eu_core", "analyze_openflights", "analyze_celegans")
    net_rows = []
    for i, src in enumerate(sources):
        series = common.read_json(src)["series"]
        net_rows += _group(SYSTEM_TEX[series[0]["system"]], i == 0)
        for rec in series:
            net_rows += _class_rows(rec["series"].replace("-degree", ""), rec, sig(rec["vmr"]))

    # Turbulence: one extra narrow column for the thinning factor k (k = 1 is
    # the full sample), so the row labels stay short enough for 390 pt.
    turb = common.read_json("analyze_turbulence")["series"]
    turb_rows = []
    for variant, title in (("full", "Turbulence, full sample (lag in ms; $k=1$)"),
                           ("thinned", "Turbulence (thinned, every $k$-th value kept; lag in ms)")):
        turb_rows += _group(title, not turb_rows, n_cols=N_COLS + 1)
        for rec in (r for r in turb if r["variant"] == variant):
            label = f"{rec['lag_ms']:g} & {rec['thinning_factor']}"
            turb_rows += _class_rows(label, rec, sig(rec["kappa2"]), blank=" & ")

    colspec = r"@{}lrrcllcr@{}"
    tail = (r"$s$ & $\hat a$ [95\% CI] & $\hat N$ [95\% CI] & "
            r"$N_{\mathrm{rd}}$ & $p$ \\")
    src_txt = ", ".join(f"results/{s}.json" for s in sources + ("analyze_turbulence",))
    write("tab_empirical.tex", header(src_txt) + rf"""{{\small
\setlength{{\tabcolsep}}{{{TABCOLSEP}}}
\begin{{tabular}}{{{colspec}}}
\toprule
Degree series & $n$ & VMR & {tail}
\midrule
{chr(10).join(net_rows)}
\bottomrule
\end{{tabular}}

\vspace{{6pt}}

\begin{{tabular}}{{@{{}}rr{colspec[4:]}}}
\toprule
Lag & $k$ & $n$ & $\kappa_2$ & {tail}
\midrule
{chr(10).join(turb_rows)}
\bottomrule
\end{{tabular}}
}}
"""
    )


def main():
    tab_topology()
    tab_power()
    tab_empirical()


if __name__ == "__main__":
    main()
